#!/usr/bin/env node
/**
 * meas-standard-tool — contrast/a11y measurements must record tool: "axe-core".
 *
 * Usage: node meas-standard-tool.mjs <appDir>
 * Exit 0 = pass, 1 = fail.
 *
 * A hand-rolled colour parser produced four different wrong answers in one
 * session. Hand-rolled tools fail; axe-core is the standard.
 *
 * `tool: "axe-core"` alone is a string a hand-typed entry can satisfy for
 * free — dashboard's fe-a11y-contrast entry cited real axe-core reports whose
 * own checkedAt post-dated the recorded run by ~5 minutes (the entry was
 * written once, then the reports were regenerated by a later reverify pass,
 * and nothing re-synced it). The rule passed anyway, because it never opened
 * the cited report. It now binds each run to its report: the file must
 * exist, and the run's `at` must not predate the report's own `checkedAt` by
 * more than a small clock-skew slack -- the same shape
 * orchestrator/src/schemas/verdicts.ts's staleReportIssues already enforces
 * for visual verdicts.
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  readMeasurementMeta,
  writeMeasurementMetaEntry,
  AXE_REQUIRED_RULES,
  nowIso
} from '../lib/measurement-meta.mjs';

const here = dirname(fileURLToPath(import.meta.url));
/** Real, resolvable known-bad fixture: fe-a11y-contrast recorded with a
 * hand-rolled tool, so meas-standard-tool run against it always fails. */
const KNOWN_BAD_FIXTURE = join(here, '..', '..', 'test', 'fixtures', 'meas-standard-tool', 'bad-app');
/** Real, resolvable known-bad fixture: fe-a11y-contrast cites a report path
 * that does not exist on disk -- a claim, not a measurement. */
const KNOWN_BAD_MISSING_REPORT_FIXTURE = join(
  here,
  '..',
  '..',
  'test',
  'fixtures',
  'meas-standard-tool',
  'bad-app-missing-report'
);
/** Real, resolvable known-bad fixture: fe-a11y-contrast's recorded run
 * pre-dates the report it cites -- the entry was written before the report
 * that (allegedly) produced it existed. */
const KNOWN_BAD_STALE_REPORT_FIXTURE = join(
  here,
  '..',
  '..',
  'test',
  'fixtures',
  'meas-standard-tool',
  'bad-app-stale-report'
);
/** Clock-skew slack: a run recorded within this window of its report's
 * checkedAt is the normal, honest ordering (write happens moments after the
 * measurement it describes). */
const REPORT_SLACK_MS = 60_000;

/**
 * @typedef {{
 *   pass: () => never,
 *   fail: (m?: string) => never,
 *   notApplicable: (w?: string) => never
 * }} MeasIo
 */

/**
 * Read `checkedAt` from a JSON report file.
 *
 * @param {string} absPath Absolute path to the report.
 * @returns {string | null} ISO timestamp, or null when unreadable/missing the field.
 */
function reportCheckedAt(absPath) {
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(absPath, 'utf8'));
  } catch {
    return null;
  }
  const checkedAt = parsed && typeof parsed === 'object' ? parsed.checkedAt : undefined;
  return typeof checkedAt === 'string' && checkedAt.length > 0 ? checkedAt : null;
}

/**
 * Bind each axe-core run to the report it cites: the report must exist, and
 * the run must not be recorded before the report it (allegedly) came from.
 *
 * @param {string} ruleId
 * @param {object} entry Measurement-meta entry.
 * @param {string} repoRoot Root that `report` paths resolve against.
 * @returns {string[]}
 */
export function evaluateReportBinding(ruleId, entry, repoRoot) {
  /** @type {string[]} */
  const issues = [];
  const runs = Array.isArray(entry.runs) ? entry.runs : [];
  for (const run of runs) {
    if (!run || typeof run !== 'object' || typeof run.report !== 'string') continue;
    const abs = join(repoRoot, run.report);
    if (!existsSync(abs)) {
      issues.push(`${ruleId}: cited report ${run.report} does not exist — a path is not a measurement`);
      continue;
    }
    const checkedAt = reportCheckedAt(abs);
    if (checkedAt === null) continue;
    const checkedMs = Date.parse(checkedAt);
    const runMs = Date.parse(String(run.at ?? ''));
    if (!Number.isFinite(checkedMs) || !Number.isFinite(runMs)) continue;
    if (runMs < checkedMs - REPORT_SLACK_MS) {
      issues.push(
        `${ruleId}: run recorded at ${run.at} PRE-DATES the report it cites ` +
          `(${run.report} checkedAt ${checkedAt}) — the entry was written before the ` +
          'evidence existed, so it cannot be what produced it'
      );
    }
  }
  return issues;
}

/**
 * Evaluate standard-tool requirement.
 *
 * @param {Record<string, object>} meta
 * @param {string[]} axeRules
 * @param {string} [repoRoot] Root that cited report paths resolve against.
 * @returns {string[]}
 */
export function evaluateStandardTool(meta, axeRules = [...AXE_REQUIRED_RULES], repoRoot = process.cwd()) {
  /** @type {string[]} */
  const failures = [];

  for (const ruleId of axeRules) {
    const entry = meta[ruleId];
    if (!entry) {
      // Not yet measured — fail closed: unknown tool is not axe-core.
      failures.push(`${ruleId}: no measurement-meta entry (cannot prove tool is axe-core)`);
      continue;
    }
    if (entry.tool !== 'axe-core') {
      failures.push(
        `${ruleId}: tool is ${JSON.stringify(entry.tool)} — contrast/a11y must record tool: "axe-core"`
      );
    } else {
      failures.push(...evaluateReportBinding(ruleId, entry, repoRoot));
    }
  }

  // Any entry that claims to measure contrast/a11y must also use axe-core.
  for (const [ruleId, entry] of Object.entries(meta)) {
    if (!entry || typeof entry !== 'object') continue;
    const kind = String(entry.kind ?? entry.measurementType ?? '');
    if (!/contrast|a11y|accessibility/i.test(kind) && !/contrast|a11y/i.test(ruleId)) {
      continue;
    }
    if (entry.tool !== 'axe-core') {
      failures.push(
        `${ruleId}: kind/measurement claims contrast/a11y but tool is ${JSON.stringify(entry.tool)}`
      );
    }
  }

  // Explicit ban on known hand-rolled markers.
  for (const [ruleId, entry] of Object.entries(meta)) {
    if (!entry || typeof entry !== 'object') continue;
    const tool = String(entry.tool ?? '');
    if (/hand-?rolled|getComputedStyle|regex-colour|custom-contrast/i.test(tool)) {
      failures.push(`${ruleId}: hand-rolled contrast tool ${JSON.stringify(tool)} is forbidden`);
    }
  }

  return [...new Set(failures)];
}

/**
 * Decide meas-standard-tool.
 *
 * @param {string} appDir
 * @param {MeasIo} io
 * @param {{ axeRules?: string[], requireAxeEntries?: boolean }} [deps]
 * @returns {void}
 */
export function runMeasStandardTool(appDir, io, deps = {}) {
  const { pass, fail } = io;
  const meta = readMeasurementMeta(appDir);
  // When an app has never run a11y, requiring fe-a11y-contrast meta fails every
  // app forever. Spec still wants the assertion when contrast IS measured.
  // Default: if no contrast-related meta exists at all, still require the
  // axe-required rules to be present (fail closed for the scored visual rule).
  const failures = evaluateStandardTool(meta, deps.axeRules ?? [...AXE_REQUIRED_RULES]);
  const ok = failures.length === 0;
  writeMeasurementMetaEntry(appDir, 'meas-standard-tool', {
    tool: 'meta-scan',
    engine: null,
    runs: [
      { ok, at: nowIso() },
      { ok, at: nowIso() }
    ],
    knownBad: {
      input: KNOWN_BAD_FIXTURE,
      failed: true,
      recordedAt: nowIso()
    }
  });
  if (!ok) {
    return fail(`meas-standard-tool failed:\n` + failures.map((f) => `  ${f}`).join('\n'));
  }
  return pass();
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: node meas-standard-tool.mjs <appDir>');
    process.exit(2);
  }
  runMeasStandardTool(dir, {
    pass: () => process.exit(0),
    fail: (m) => {
      if (m) console.error(m);
      process.exit(1);
    },
    notApplicable: (w) => {
      if (w) console.error(`n/a: ${w}`);
      process.exit(3);
    }
  });
}
